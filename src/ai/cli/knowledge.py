"""``ai knowledge``: build and manage the project knowledge used by the agents."""
from ai.cli.base import SUPPRESS, add_actions, add_command

NAME = "knowledge"
HELP = "Build, list or forget the project knowledge of this folder"
DESCRIPTION = """Project knowledge: one component JSON and one Markdown doc per source file,
generated by the model and loaded automatically when agents work in this folder.

  ai knowledge build               this folder: src/ (or .), only new/changed files
  ai knowledge build src --ext py,ts --mode all
  ai knowledge build --mode diff:master
  ai knowledge list                sources registered here, and coverage
  ai knowledge forget ID           stop loading a source
"""

DEFAULTS = {
    "build_knowledge": None, "kb_mode": "changed", "kb_only": None, "kb_ext": None,
    "kb_files": None, "kb_max": 0, "kb_force": False,
    "knowledge_list": False, "knowledge_forget": None,
}

LEGACY = {
    "--build-knowledge": "ai knowledge build",
    "--kb-mode": "ai knowledge build --mode", "--kb-only": "ai knowledge build --only",
    "--kb-ext": "ai knowledge build --ext", "--kb-files": "ai knowledge build --files",
    "--kb-max": "ai knowledge build --max", "--kb-force": "ai knowledge build --force",
    "--knowledge-list": "ai knowledge list",
    "--knowledge-forget": "ai knowledge forget",
}


def register(subparsers, parent):
    parser = add_command(subparsers, NAME, HELP, DESCRIPTION, usage="%(prog)s ACTION [OPTIONS]")
    actions = add_actions(parser, "knowledge_command")

    build = add_command(actions, "build", "Generate docs and component knowledge with the model",
                        usage="%(prog)s [SRC] [OPTIONS]")
    build.add_argument("--model", "-md", type=str, help="Model config to generate with (default: MODEL_CONFIG_NAME)")
    build.add_argument("build_knowledge", nargs="?", metavar="SRC", help="Source root (default: src/ if it exists, else .)")
    build.add_argument("--mode", dest="kb_mode", metavar="MODE",
                       help="missing | changed (default) | all | diff[:branch]")
    build.add_argument("--only", dest="kb_only", choices=["docs", "knowledge"], help="Generate only docs or only knowledge")
    build.add_argument("--ext", dest="kb_ext", metavar="EXTS", help="Source extensions, comma separated, or 'all' for every text file (default: the last build's, then KNOWLEDGE_EXTENSIONS, then all)")
    build.add_argument("--files", dest="kb_files", metavar="FILES", help="Only these files, comma separated")
    build.add_argument("--max", dest="kb_max", type=int, metavar="N", help="Stop after N files")
    build.add_argument("--force", dest="kb_force", action="store_true", help="Regenerate files that are up to date")
    build.set_defaults(build_knowledge="")

    add_command(actions, "list", "Show the knowledge registered for this folder", usage="%(prog)s").set_defaults(knowledge_list=True)

    forget = add_command(actions, "forget", "Stop loading a registered knowledge source for this folder",
                         usage="%(prog)s SOURCE_ID")
    forget.add_argument("knowledge_forget", metavar="SOURCE_ID")


